from __future__ import annotations

import re
import unicodedata
from collections import Counter

CJK_RANGES = (
    (0x3400, 0x4DBF),
    (0x4E00, 0x9FFF),
    (0xF900, 0xFAFF),
    (0x3040, 0x30FF),  # Hiragana + Katakana (documents may contain them)
    (0xAC00, 0xD7AF),  # Hangul syllables
    (0x20000, 0x2FA1F),
)

_WS_RE = re.compile(r"\s+")
_EDGE_PUNCT_RE = re.compile(r"^[^\w㐀-鿿豈-﫿]+|[^\w㐀-鿿豈-﫿]+$")


def is_cjk(ch: str) -> bool:
    code = ord(ch)
    return any(lo <= code <= hi for lo, hi in CJK_RANGES)


def normalize_text(text: str) -> str:
    if not text:
        return ""
    text = unicodedata.normalize("NFKC", text)
    text = text.replace(" ", " ").replace("　", " ")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return text


def _iter_runs(text: str):
    """Yield (is_cjk, run_text) for contiguous CJK and word runs."""
    buffer: list[str] = []
    mode: bool | None = None
    for ch in text:
        if is_cjk(ch):
            this_mode = True
        elif ch.isalnum() or ch == "_":
            this_mode = False
        else:
            if buffer and mode is not None:
                yield mode, "".join(buffer)
            buffer = []
            mode = None
            continue
        if mode is None:
            mode = this_mode
        if mode != this_mode:
            yield mode, "".join(buffer)
            buffer = []
            mode = this_mode
        buffer.append(ch)
    if buffer and mode is not None:
        yield mode, "".join(buffer)


def tokenize_for_fts(text: str) -> str:
    """Tokenize text into whitespace-separated FTS5 tokens.

    CJK text is indexed as overlapping bigrams. For example 项目合同 -> 项目 目合 合同.
    Latin/alphanumeric text is lowercased and kept as word tokens.
    """
    text = normalize_text(text)
    tokens: list[str] = []
    for is_cjk_run, run in _iter_runs(text):
        if is_cjk_run:
            if len(run) == 1:
                tokens.append(run)
            else:
                tokens.extend(run[i : i + 2] for i in range(len(run) - 1))
        else:
            tokens.append(run.lower())
    return " ".join(tokens)


def _quote(token: str) -> str:
    token = token.replace('"', "")
    return f'"{token}"'


def build_fts_query(text: str, operator: str = "AND") -> str | None:
    """Build a safe FTS5 MATCH expression from user text.

    Each CJK run is expressed as a phrase of bigrams so that 项目合同 requires
    the characters to be adjacent. Latin words are quoted individually.
    """
    text = normalize_text(text).strip()
    if not text:
        return None
    # User-provided quotes are treated as grouping hints only; all syntax is
    # generated by us so arbitrary FTS5 operators cannot be injected.
    text = text.replace('"', " ").replace("“", " ").replace("”", " ")
    groups: list[str] = []
    for is_cjk_run, run in _iter_runs(text):
        if not run.strip():
            continue
        if is_cjk_run:
            if len(run) == 1:
                groups.append(_quote(run))
            else:
                bigrams = [run[i : i + 2] for i in range(len(run) - 1)]
                groups.append('"' + " ".join(bigrams) + '"')
        else:
            word = run.strip()
            if word:
                groups.append(_quote(word))
    if not groups:
        return None
    return f" {operator} ".join(groups)


def search_phrase_terms(text: str) -> list[str]:
    """Original content segments used for highlighting snippets."""
    text = normalize_text(text).strip()
    terms: list[str] = []
    for is_cjk_run, run in _iter_runs(text):
        run = run.strip()
        if len(run) < (1 if is_cjk_run else 2):
            continue
        terms.append(run)
    return terms


def extract_keywords(text: str, top_k: int = 20) -> list[tuple[str, float]]:
    """Extract document keywords for related-document explanations.

    jieba is used here only; the FTS index uses deterministic bigrams so query
    behavior never depends on jieba's dictionary.
    """
    text = normalize_text(text)
    text = text[:200_000]
    if not text.strip():
        return []
    try:
        import jieba.analyse

        pairs = jieba.analyse.extract_tags(text, topK=top_k, withWeight=True)
        result: list[tuple[str, float]] = []
        for word, weight in pairs:
            word = word.strip().lower()
            if len(word) >= 2 and not word.isdigit():
                result.append((word, float(weight)))
        if result:
            return result
    except Exception:
        pass

    # Lightweight fallback if jieba is unavailable.
    tokens = tokenize_for_fts(text).split()
    counts = Counter(tokens)
    total = max(1, sum(counts.values()))
    return [
        (token, count / total)
        for token, count in counts.most_common(top_k)
        if len(token) >= 2
    ]


def normalize_path_for_search(path: str) -> str:
    return unicodedata.normalize("NFC", path)
